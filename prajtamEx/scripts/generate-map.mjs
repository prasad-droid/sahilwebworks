import { readFile, writeFile } from "node:fs/promises";

const SRC = new URL("./data/ne_110m_admin_0_countries.geojson", import.meta.url);
const OUT = new URL("../src/data/worldMap.js", import.meta.url);

const MAP_WIDTH = 1000;
const MAP_HEIGHT = 400;
const LAT_TOP = 84;
const LAT_BOTTOM = -60;
const MIN_RING_AREA = 1.4;

const project = (lon, lat) => [
  ((lon + 180) / 360) * MAP_WIDTH,
  ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * MAP_HEIGHT,
];

const round = (n) => Math.round(n * 10) / 10;

function ringArea(ring) {
  let area = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    area += ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1];
  }
  return Math.abs(area / 2);
}

function ringToPath(ring, minGap) {
  let d = "";
  let prev = null;
  let first = null;
  for (const [lon, lat] of ring) {
    if (lon < -180 || lon > 180 || lat < LAT_BOTTOM - 5 || lat > LAT_TOP + 6) continue;
    const [x, y] = project(lon, lat);
    const pt = [round(x), round(y)];
    if (prev && Math.abs(pt[0] - prev[0]) + Math.abs(pt[1] - prev[1]) < minGap) continue;
    if (!first) {
      first = pt;
      d += `M${pt[0]},${pt[1]}`;
    } else {
      d += `L${pt[0]},${pt[1]}`;
    }
    prev = pt;
  }
  if (!first) return "";
  return d + "Z";
}

const geo = JSON.parse(await readFile(SRC, "utf8"));
const countries = [];

for (const feature of geo.features) {
  const props = feature.properties || {};
  const iso = props.ADM0_A3 || props.ISO_A3 || "";
  if (iso === "ATA" || props.ADMIN === "Antarctica") continue;

  const geom = feature.geometry;
  if (!geom) continue;
  const polygons = geom.type === "Polygon" ? [geom.coordinates] : geom.type === "MultiPolygon" ? geom.coordinates : [];

  const parts = [];
  for (const polygon of polygons) {
    for (const ring of polygon) {
      const projected = ring.map(([lon, lat]) => project(lon, lat));
      if (ringArea(projected) < MIN_RING_AREA) continue;
      const d = ringToPath(ring, 0.7);
      if (d) parts.push(d);
    }
  }
  if (!parts.length) continue;

  countries.push({
    id: iso || props.ISO_A2 || props.ADMIN,
    name: props.ADMIN || props.NAME || "",
    d: parts.join(""),
  });
}

countries.sort((a, b) => a.name.localeCompare(b.name));

const banner = `/* Generated by scripts/generate-map.mjs — Natural Earth 1:110m, equirectangular. */\n`;
const body = `${banner}export const MAP_WIDTH = ${MAP_WIDTH};
export const MAP_HEIGHT = ${MAP_HEIGHT};
export const MAP_LON_RANGE = [-180, 180];
export const MAP_LAT_RANGE = [${LAT_TOP}, ${LAT_BOTTOM}];

export function project(lon, lat) {
  const x = ((lon + 180) / 360) * MAP_WIDTH;
  const y = ((${LAT_TOP} - lat) / (${LAT_TOP} - (${LAT_BOTTOM}))) * MAP_HEIGHT;
  return [x, y];
}

export const WORLD_COUNTRIES = ${JSON.stringify(countries)};
`;

await writeFile(OUT, body, "utf8");
console.log(`Wrote ${countries.length} countries (${Math.round(body.length / 1024)}KB)`);
